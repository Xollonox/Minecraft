/**
 * Biomes that participate in climate-space blending. Ocean, beach and peaks are
 * assigned by elevation instead.
 */
const CLIMATE_BIOMES = BIOMES.filter(
  (definition) =>
    !definition.underground &&
    // Nether biomes live in the same table so that biome ids stay globally
    // unique, but they are chosen by NetherGenerator, never blended here.
    !definition.nether &&
    definition.id !== Biome.OCEAN &&
    definition.id !== Biome.BEACH &&
    definition.id !== Biome.SNOWY_PEAKS
);

/** Y level at which permanent snow begins, before temperature adjustment. */
const SNOW_LINE = SEA_LEVEL + 38;
/** Height above which surfaces turn to bare stone. */
const STONE_LINE = SEA_LEVEL + 30;

/**
 * @typedef {Object} ColumnSample
 * @property {number} height Y of the highest generated terrain block.
 * @property {number} biome Biome id.
 * @property {number} temperature
 * @property {number} moisture
 * @property {number} continentalness
 * @property {number} erosion
 * @property {number} surface Surface block id.
 * @property {number} subsurface Subsurface block id.
 * @property {number} subsurfaceDepth
 * @property {boolean} underwater True when the surface is below sea level.
 * @property {boolean} snowy
 */

export class BiomeGenerator {
  /**
   * @param {number} seed
   */
  constructor(seed) {
    this.seed = seed >>> 0;
    this._noise = new NoiseSet(this.seed, [
      'continental',
      'erosion',
      'hills',
      'ridge',
      'temperature',
      'moisture',
      'warp',
      'detail',
      'beach',
    ]);

    /** Reused sample object for the hot path. */
    this._sample = createColumnSample();
    /** Scratch weight buffer, one slot per climate biome. */
    this._weights = new Float64Array(CLIMATE_BIOMES.length);
  }

  /**
   * Full climate + landform sample for a world column.
   *
   * @param {number} worldX
   * @param {number} worldZ
   * @param {ColumnSample} [out] Optional target to avoid allocation.
   * @returns {ColumnSample}
   */
  sampleColumn(worldX, worldZ, out = this._sample) {
    const continental = this._noise.get('continental');
    const erosionNoise = this._noise.get('erosion');
    const hillsNoise = this._noise.get('hills');
    const ridgeNoise = this._noise.get('ridge');
    const warpNoise = this._noise.get('warp');
    const detailNoise = this._noise.get('detail');

    // --- domain warp -------------------------------------------------------
    // Offsetting the sample point by low-frequency noise makes coastlines and
    // biome edges meander instead of following the noise grid.
    const warpX = warpNoise.noise2(worldX * 0.0009, worldZ * 0.0009) * 48;
    const warpZ = warpNoise.noise2(worldX * 0.0009 + 7.31, worldZ * 0.0009 - 3.17) * 48;
    const wx = worldX + warpX;
    const wz = worldZ + warpZ;

    // --- landform fields ---------------------------------------------------
    // Continentalness: very low frequency, decides land vs. sea.
    const continentalness = continental.fbm2(wx, wz, 4, 0.00042, 2.1, 0.5);
    // Erosion: high erosion flattens terrain, low erosion lets relief through.
    const erosion = erosionNoise.fbm2(wx, wz, 3, 0.0011, 2.0, 0.5);
    // Hilliness: mid-frequency rolling relief.
    const hills = hillsNoise.fbm2(wx, wz, 4, 0.0055, 2.0, 0.5);
    // Ridges: sharp mountain spines, masked so they only appear inland.
    const ridge = ridgeNoise.ridged2(wx, wz, 4, 0.0026, 2.05, 0.5) * 2 - 1;

    // --- climate fields ----------------------------------------------------
    let temperature = this._noise.get('temperature').fbm2(wx, wz, 3, 0.00058, 2.0, 0.5) * 1.35;
    let moisture = this._noise.get('moisture').fbm2(wx, wz, 3, 0.00071, 2.0, 0.5) * 1.35;
    temperature = clamp(temperature, -1, 1);
    moisture = clamp(moisture, -1, 1);

    // --- blended height ----------------------------------------------------
    // Relief is shared across biomes so a blend of two biomes never produces a
    // step; only the amplitude and target height differ per biome.
    const erosionFactor = lerp(1, 0.28, clamp01((erosion + 1) * 0.5));
    const inlandMask = smoothstep(-0.08, 0.42, continentalness);
    const relief =
      hills * 9 * erosionFactor + Math.max(0, ridge) * 26 * inlandMask * erosionFactor;

    const weights = this._weights;
    let weightSum = 0;
    for (let i = 0; i < CLIMATE_BIOMES.length; i++) {
      const definition = CLIMATE_BIOMES[i];
      const dt = temperature - definition.temperature;
      const dm = moisture - definition.moisture;
      // Inverse square distance with a floor: nearby biomes dominate, distant
      // ones still contribute a little, and nothing divides by zero.
      const weight = 1 / (dt * dt + dm * dm + 0.035) ** 1.9;
      weights[i] = weight;
      weightSum += weight;
    }

    let blendedBase = 0;
    let blendedAmplitude = 0;
    let blendedRoughness = 0;
    let dominantIndex = 0;
    let dominantWeight = -1;
    for (let i = 0; i < CLIMATE_BIOMES.length; i++) {
      const normalised = weights[i] / weightSum;
      const definition = CLIMATE_BIOMES[i];
      blendedBase += definition.baseHeight * normalised;
      blendedAmplitude += definition.amplitude * normalised;
      blendedRoughness += definition.roughness * normalised;
      if (weights[i] > dominantWeight) {
        dominantWeight = weights[i];
        dominantIndex = i;
      }
    }

    // Ocean basins: pull the whole column down where continentalness is low.
    const oceanDepth = smoothstep(0.05, -0.55, continentalness);
    const landHeight = blendedBase + relief * blendedAmplitude;
    const oceanFloor = SEA_LEVEL - 6 - 26 * oceanDepth + hills * 4;
    let height = lerp(landHeight, oceanFloor, oceanDepth);

    // Small-scale detail so flat biomes are not billiard tables.
    height += detailNoise.fbm2(wx, wz, 3, 0.045, 2.0, 0.5) * 1.6 * blendedRoughness;

    height = Math.round(clamp(height, 2, WORLD_HEIGHT - 12));

    // --- classification ----------------------------------------------------
    let biomeId = CLIMATE_BIOMES[dominantIndex].id;
    const underwater = height < SEA_LEVEL;

    if (height <= SEA_LEVEL - 3) {
      if (oceanDepth > 0.72) biomeId = Biome.DEEP_OCEAN;
      else if (temperature < -0.65) biomeId = Biome.FROZEN_OCEAN;
      else if (temperature < -0.25) biomeId = Biome.COLD_OCEAN;
      else if (temperature > 0.65) biomeId = Biome.WARM_OCEAN;
      else if (temperature > 0.25) biomeId = Biome.LUKEWARM_OCEAN;
      else biomeId = Biome.OCEAN;
    } else if (height <= SEA_LEVEL + 1) {
      // Only sand the shoreline where the land is genuinely low and flat; a
      // cliff dropping into the sea should stay stone.
      const beachiness = this._noise.get('beach').noise2(worldX * 0.02, worldZ * 0.02);
      if (beachiness > -0.35) biomeId = Biome.BEACH;
    } else if (height >= STONE_LINE) {
      const snowBias = SNOW_LINE - temperature * 14;
      biomeId = height >= snowBias ? Biome.SNOWY_PEAKS : Biome.MOUNTAINS;
    }

    const definition = BIOME_BY_ID[biomeId];

    out.height = height;
    out.biome = biomeId;
    out.temperature = temperature;
    out.moisture = moisture;
    out.continentalness = continentalness;
    out.erosion = erosion;
    out.surface = definition.surface;
    out.subsurface = definition.subsurface;
    out.subsurfaceDepth = definition.subsurfaceDepth;
    out.underwater = underwater;
    out.snowy = definition.snowy || (height > SNOW_LINE - temperature * 14 && temperature < 0.1);
    return out;
  }

  /**
   * Surface height only. Structures need heights outside the chunk they are
   * decorating, and this keeps that call site honest about the cost.
   *
   * @param {number} worldX
   * @param {number} worldZ
   * @returns {number}
   */
  getSurfaceHeight(worldX, worldZ) {
    return this.sampleColumn(worldX, worldZ, this._sample).height;
  }
}

/** Biome definition lookup by id. */
export function getBiome(id) {
  return BIOME_BY_ID[id] || BIOME_BY_ID[Biome.PLAINS];
}

/** Display name for a biome id. */
export function getBiomeName(id) {
  return BIOME_BY_ID[id]?.name ?? 'Unknown';
}

/** Allocates a fresh column sample object. */
export function createColumnSample() {
  return {
    height: SEA_LEVEL,
    biome: Biome.PLAINS,
    temperature: 0,
    moisture: 0,
    continentalness: 0,
    erosion: 0,
    surface: Block.GRASS,
    subsurface: Block.DIRT,
    subsurfaceDepth: 4,
    underwater: false,
    snowy: false,
  };
}

export default BiomeGenerator;
