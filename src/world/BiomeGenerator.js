/**
 * Biome selection and terrain-shape blending.
 *
 * The generator is a small climate model rather than a lookup on one height
 * noise:
 *
 *  1. Four independent *shape* fields (continentalness, erosion, hilliness and
 *     a ridge field) decide the raw landform.
 *  2. Two independent *climate* fields (temperature and moisture), warped and
 *     biased by altitude, place the column in climate space.
 *  3. Every land biome sits at a point in that climate space. Column height is
 *     the weighted blend of each biome's own height profile, weighted by
 *     inverse-square distance in climate space. That blend is what removes the
 *     hard cliff you otherwise get where a desert meets a forest — the terrain
 *     shape morphs continuously even though the surface block changes at a
 *     discrete boundary.
 *  4. Ocean, beach and mountain classification happens *after* the height is
 *     known, because those are consequences of elevation rather than climate.
 *
 * Every function here is a pure function of (seed, x, z), so two neighbouring
 * chunks generated by two different workers agree exactly on their shared edge.
 *
 * Worker-safe.
 */

